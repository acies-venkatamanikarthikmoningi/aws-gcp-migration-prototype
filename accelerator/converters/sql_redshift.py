"""Redshift SQL -> BigQuery GoogleSQL.

sqlglot does the dialect transpile; deterministic Redshift rules handle what it cannot:
DIST/SORT keys -> PARTITION BY / CLUSTER BY, ENCODE, IDENTITY, PRIMARY KEY NOT ENFORCED, STRING_AGG ordering,
COPY -> LOAD DATA, UNLOAD -> EXPORT DATA, VACUUM/ANALYZE removal. Anything else unknown is reported.
"""
from __future__ import annotations

import logging
import re
from pathlib import Path

import sqlglot
from sqlglot import exp

from .common import ConversionResult

S3_TO_GCS = re.compile(r"s3://([a-z0-9.\-]+)")


def _split_statements(sql: str) -> list[str]:
    out, buf, q = [], [], False
    for ch in sql:
        if ch == "'":
            q = not q
        if ch == ";" and not q:
            s = "".join(buf).strip()
            if s:
                out.append(s)
            buf = []
        else:
            buf.append(ch)
    tail = "".join(buf).strip()
    if tail:
        out.append(tail)
    return out


def _strip_comments(s: str) -> str:
    return "\n".join(line for line in s.splitlines() if not line.strip().startswith("--")).strip()


def _table_layout(raw: str, columns: dict[str, str]) -> tuple[str, list[str]]:
    notes = []
    dist = re.search(r"DISTKEY\s*\(\s*(\w+)\s*\)", raw, re.I)
    sort = re.search(r"(?:COMPOUND\s+|INTERLEAVED\s+)?SORTKEY\s*\(([^)]*)\)", raw, re.I)
    sort_cols = [c.strip() for c in sort.group(1).split(",")] if sort else []
    partition = ""
    cluster: list[str] = []
    for c in sort_cols:
        t = columns.get(c.lower(), "")
        if not partition and t in ("DATE", "TIMESTAMP", "DATETIME"):
            partition = f"PARTITION BY {c}" if t == "DATE" else f"PARTITION BY DATE({c})"
            notes.append(f"SORTKEY {c} ({t}) -> {partition}")
        else:
            cluster.append(c)
    if dist:
        cluster.insert(0, dist.group(1))
        notes.append(f"DISTKEY {dist.group(1)} -> leading CLUSTER BY column")
    cluster = list(dict.fromkeys(cluster))[:4]
    clause = " ".join(x for x in [partition, f"CLUSTER BY {', '.join(cluster)}" if cluster else ""] if x)
    if re.search(r"INTERLEAVED\s+SORTKEY", raw, re.I):
        notes.append("INTERLEAVED SORTKEY has no equivalent – review query patterns")
    if re.search(r"DISTSTYLE\s+ALL", raw, re.I):
        notes.append("DISTSTYLE ALL (broadcast) not needed in BigQuery – review small dimension joins")
    return clause, notes


def _columns(raw: str) -> dict[str, str]:
    cols = {}
    body = raw[raw.find("(") + 1: raw.rfind(")")]
    for line in body.split(","):
        m = re.match(r"\s*(\w+)\s+(\w+)", line)
        if m and m.group(1).upper() not in ("PRIMARY", "FOREIGN", "UNIQUE", "CONSTRAINT"):
            t = m.group(2).upper()
            cols[m.group(1).lower()] = {"TIMESTAMP": "DATETIME", "TIMESTAMPTZ": "TIMESTAMP"}.get(t, t)
    return cols


def convert_copy(raw: str, res: ConversionResult) -> str:
    m = re.search(r"COPY\s+([\w.]+)\s+FROM\s+'([^']+)'", raw, re.I)
    fmt = "PARQUET" if re.search(r"PARQUET", raw, re.I) else "CSV" if re.search(r"CSV", raw, re.I) else "PARQUET"
    uri = S3_TO_GCS.sub(r"gs://\1", m.group(2)).rstrip("/") + "/*"
    res.assumptions.append(f"COPY source {m.group(2)} mirrored to {uri} by the data migration pipeline")
    res.warnings.append("IAM_ROLE clause dropped – BigQuery uses the caller/service account permissions")
    return f"LOAD DATA INTO {m.group(1)}\nFROM FILES (format = '{fmt}', uris = ['{uri}'])"


def convert_unload(raw: str, res: ConversionResult) -> str:
    m = re.search(r"UNLOAD\s*\(\s*'(.*?)'\s*\)\s*TO\s*'([^']+)'", raw, re.I | re.S)
    inner, target = m.group(1).replace("''", "'"), S3_TO_GCS.sub(r"gs://\1", m.group(2))
    fmt = "PARQUET" if re.search(r"PARQUET", raw, re.I) else "CSV"
    q = sqlglot.transpile(inner, read="redshift", write="bigquery")[0]
    return (f"EXPORT DATA OPTIONS (uri = '{target}*.{fmt.lower()}', format = '{fmt}', overwrite = true) AS\n{q}")


def post_rules(sql: str, res: ConversionResult) -> str:
    before = sql
    sql = re.sub(r"\s+ENCODE\s+\w+", "", sql, flags=re.I)
    if sql != before:
        res.mapping_log.append({"rule": "ENCODE removed", "detail": "BigQuery manages columnar compression"})
    if re.search(r"GENERATED BY DEFAULT AS IDENTITY[^,\n]*", sql):
        sql = re.sub(r"\s*GENERATED BY DEFAULT AS IDENTITY\s*\([^)]*\)", "", sql)
        res.warnings.append("IDENTITY column has no BigQuery equivalent – assign keys in the load pipeline "
                            "(preserve source values during backfill; GENERATE_UUID()/ROW_NUMBER for new rows)")
    sql = re.sub(r"PRIMARY KEY \(([^)]*)\)(?! NOT ENFORCED)", r"PRIMARY KEY (\1) NOT ENFORCED", sql)
    sql = re.sub(r"(\w+ DATETIME) DEFAULT CURRENT_TIMESTAMP\(\)", r"\1 DEFAULT CURRENT_DATETIME()", sql)
    # STRING_AGG(x, ',') WITHIN GROUP (ORDER BY y [NULLS LAST]) -> STRING_AGG(x, ',' ORDER BY y)
    sql = re.sub(r"STRING_AGG\(([^,]+),\s*('[^']*')\)\s*WITHIN GROUP\s*\(\s*ORDER BY\s+([^)]*?)(?:\s+NULLS LAST)?\s*\)",
                 lambda m: f"STRING_AGG({m.group(1)}, {m.group(2)} ORDER BY {' '.join(m.group(3).split())})", sql, flags=re.S)
    return sql


def convert_sql(path: Path) -> ConversionResult:
    res = ConversionResult("redshift-sql-to-bigquery", path.name)
    text = path.read_text(encoding="utf-8")
    out_parts = ["-- GENERATED by AWS-to-GCP Migration Accelerator (Redshift -> BigQuery GoogleSQL). Review before execution."]
    logging.getLogger("sqlglot").setLevel(logging.ERROR)
    for raw in _split_statements(text):
        stmt = _strip_comments(raw)
        if not stmt:
            continue
        res.constructs_total += 1
        head = stmt.split(None, 1)[0].upper()
        try:
            if head in ("VACUUM", "ANALYZE"):
                out_parts.append(f"-- removed: {stmt.splitlines()[0]} (BigQuery storage optimisation is automatic)")
                res.mapping_log.append({"rule": f"{head} removed"})
                res.constructs_converted += 1
                continue
            if head == "COPY":
                out_parts.append(convert_copy(stmt, res) + ";")
                res.constructs_converted += 1
                continue
            if head == "UNLOAD":
                out_parts.append(convert_unload(stmt, res) + ";")
                res.constructs_converted += 1
                continue
            if head in ("GRANT", "REVOKE", "CREATE USER", "ALTER USER"):
                res.unsupported.append(f"{head}: map Redshift users/groups to IAM roles / dataset ACLs")
                out_parts.append(f"-- UNSUPPORTED (security): {stmt.splitlines()[0]}")
                continue
            if re.match(r"CREATE\s+(OR\s+REPLACE\s+)?PROCEDURE", stmt, re.I):
                res.unsupported.append("Stored procedure (PL/pgSQL) -> rewrite as BigQuery scripting procedure")
                out_parts.append(f"-- UNSUPPORTED: {stmt.splitlines()[0]} (manual rewrite)")
                continue
            tree = sqlglot.parse_one(stmt, read="redshift")
            if isinstance(tree, exp.Command):
                res.unsupported.append(f"{head}: not translatable")
                out_parts.append(f"-- UNSUPPORTED: {stmt.splitlines()[0]}")
                continue
            sql = tree.sql(dialect="bigquery", pretty=True, unsupported_level=sqlglot.ErrorLevel.IGNORE)
            sql = post_rules(sql, res)
            if isinstance(tree, exp.Create):
                clause, notes = _table_layout(stmt, _columns(stmt))
                for n in notes:
                    res.mapping_log.append({"rule": "table layout", "detail": n})
                if clause:
                    sql = sql.rstrip() + "\n" + clause
            if re.search(r"APPROXIMATE", stmt, re.I):
                res.assumptions.append("APPROXIMATE COUNT(DISTINCT) -> APPROX_COUNT_DISTINCT (HLL++; error profile differs)")
            if re.search(r"CONVERT_TIMEZONE", stmt, re.I):
                res.warnings.append("CONVERT_TIMEZONE translated via DATETIME/TIMESTAMP casts – validate DST edge cases")
            out_parts.append(sql + ";")
            res.constructs_converted += 1
        except Exception as e:  # noqa: BLE001
            res.unsupported.append(f"{head}: parse error {str(e)[:120]}")
            out_parts.append(f"-- FAILED TO CONVERT: {stmt.splitlines()[0]}")
    out = "\n\n".join(out_parts) + "\n"
    res.outputs["sql/bigquery_customer.sql"] = out
    # static check: every emitted statement must re-parse as BigQuery
    bad = []
    for s in _split_statements(out):
        s = _strip_comments(s)
        if not s or s.startswith("LOAD DATA") or s.startswith("EXPORT DATA"):
            continue
        try:
            sqlglot.parse_one(s, read="bigquery")
        except Exception as e:  # noqa: BLE001
            bad.append(str(e)[:80])
    res.checks.append({"check": "BigQuery dialect re-parse", "status": "FAIL" if bad else "PASS", "detail": "; ".join(bad)})
    res.checks.append({"check": "dry-run on BigQuery", "status": "NOT_RUN",
                       "detail": "requires approved GCP project: bq query --dry_run"})
    return res
