"""Communications and dependency follow-through (project document phase 8, component 10; Round 6).

Three things a person records, because the tool cannot observe them:

1. The e-mail lifecycle. Drafts are generated by the tool; a person approves (or edits, then approves) each one, sends it from
   their own mail client, and records that it was sent, that it bounced, or what the reply said. Nothing is sent from here.
   An approval is tied to the exact text approved: if the text changes afterwards, the approval lapses.
2. Each application's migration status: still on AWS, cutover in progress, or on Google Cloud. Recording a start or a
   completion is what produces the "Migration started" and "Migration completed" drafts, to the application's own owner and
   to the owners of every application downstream of it.
3. Dependency confirmations: an owner confirms that an inferred link is real, or says it is not; and, where a downstream
   application will stay on AWS for a while, a person records that its owner agreed a bridge (dual run, copy back, or similar).
"""
from __future__ import annotations

import hashlib
import json
import re

from .store import Store, now

APP_STATUSES = ("NOT_STARTED", "IN_PROGRESS", "MIGRATED")
APP_LABEL = {"NOT_STARTED": "Still on AWS", "IN_PROGRESS": "Cutover in progress", "MIGRATED": "On Google Cloud"}
EDGE_OUTCOMES = ("OWNER_CONFIRMED", "OWNER_REVERSED", "OWNER_REJECTED")
# Link types whose arrow points from the reader to what it reads (data flows the other way). Every other type points
# the way data or control flows. Links found by inference (Terraform references, diagrams) have no reliable direction
# until an owner confirms it.
REVERSE_TYPES = {"READS_FROM"}


def flow(edge: dict) -> str:
    """FORWARD (data flows source to target), REVERSE, UNCONFIRMED (inferred, no owner answer yet) or REJECTED."""
    oc = edge.get("owner_status")
    if oc == "OWNER_REJECTED":
        return "REJECTED"
    base = "REVERSE" if edge.get("type") in REVERSE_TYPES else "FORWARD"
    if oc == "OWNER_REVERSED":
        return "FORWARD" if base == "REVERSE" else "REVERSE"
    if oc == "OWNER_CONFIRMED" or edge.get("status") == "CONFIRMED":
        return base
    return "UNCONFIRMED"
REPLY_OUTCOMES = ("ACKNOWLEDGED", "QUESTION", "OBJECTION")


def _sid(prefix: str, *parts: str) -> str:
    return prefix + hashlib.sha256("|".join(parts).encode()).hexdigest()[:16]


def _need(text: str, what: str, n: int = 2) -> str:
    text = (text or "").strip()
    if len(text) < n:
        raise ValueError(f"Enter {what}" + (f" (at least {n} characters)." if n > 2 else "."))
    return text


# --------------------------------------------------------------------------- application migration status
def app_statuses(store: Store, pid: str) -> dict[str, dict]:
    return {r["application"]: r for r in store.all("app_migration_status", project_id=pid)}


def status_of(statuses: dict[str, dict], app: str) -> str:
    return (statuses.get(app) or {}).get("status") or "NOT_STARTED"


def set_app_status(store: Store, pid: str, application: str, status: str, by: str, note: str, readiness: str | None) -> dict:
    """readiness is the application's current readiness when it belongs to this project, None for an application outside it
    (a downstream consumer whose team tells us where it stands)."""
    if status not in APP_STATUSES:
        raise ValueError(f"Status must be one of {', '.join(APP_STATUSES)}.")
    by = _need(by, "who is recording this")
    note = _need(note, "a note saying what happened or who told you", 10)
    cur = status_of(app_statuses(store, pid), application)
    if status == cur:
        raise ValueError(f"{application} is already recorded as {APP_LABEL[status].lower()}.")
    if readiness is not None and status == "IN_PROGRESS" and cur == "NOT_STARTED" and readiness != "SIGNED_OFF":
        raise ValueError(f"{application} cannot start cutover: it is {readiness.replace('_', ' ').lower()}, not signed off. "
                         "Clear its gates and record business and technical sign-off first.")
    if status == "MIGRATED" and cur != "IN_PROGRESS" and readiness is not None:
        raise ValueError(f"Record that cutover of {application} has started before recording it as complete.")
    row = store.insert("app_migration_status", {"id": _sid("AMS-", pid, application), "project_id": pid, "application": application,
                                                "status": status, "note": note, "updated_by": by, "updated_at": now()})
    store.audit(pid, by, "APP_MIGRATION_STATUS_SET", "application", application,
                {"from": cur, "to": status, "note": note, "in_project": readiness is not None})
    return row


# --------------------------------------------------------------------------- dependency confirmations
def confirmations(store: Store, pid: str) -> list[dict]:
    return store.all("dependency_confirmations", project_id=pid)


def edge_outcomes(store: Store, pid: str) -> dict[tuple[str, str], dict]:
    return {(c["source"], c["target"]): c for c in confirmations(store, pid) if c["kind"] == "EDGE"}


def bridges(store: Store, pid: str) -> dict[tuple[str, str], dict]:
    return {(c["source"], c["target"]): c for c in confirmations(store, pid) if c["kind"] == "BRIDGE"}


def confirm_edge(store: Store, pid: str, source: str, target: str, outcome: str, by: str, note: str, known_edges: set) -> dict:
    if outcome not in EDGE_OUTCOMES + ("CLEAR",):
        raise ValueError("Outcome must be OWNER_CONFIRMED, OWNER_REVERSED, OWNER_REJECTED or CLEAR.")
    if (source, target) not in known_edges:
        raise ValueError("That link is not in the dependency graph.")
    cid = _sid("DCF-", pid, "EDGE", source, target)
    if outcome == "CLEAR":
        store.delete_where("dependency_confirmations", id=cid)
        store.audit(pid, by or "console.user", "DEPENDENCY_CONFIRMATION_CLEARED", "dependency", f"{source}->{target}", {})
        return {"source": source, "target": target, "outcome": None}
    by = _need(by, "the owner's name")
    note = _need(note, "what the owner said", 5)
    row = store.insert("dependency_confirmations", {"id": cid, "project_id": pid, "kind": "EDGE", "source": source, "target": target,
                                                    "outcome": outcome, "by_name": by, "note": note, "recorded_at": now()})
    store.audit(pid, by, f"DEPENDENCY_{outcome}", "dependency", f"{source}->{target}", {"note": note})
    return row


def agree_bridge(store: Store, pid: str, upstream_app: str, downstream_app: str, by: str, note: str, clear: bool = False) -> dict:
    cid = _sid("DCF-", pid, "BRIDGE", upstream_app, downstream_app)
    if clear:
        store.delete_where("dependency_confirmations", id=cid)
        store.audit(pid, by or "console.user", "BRIDGE_AGREEMENT_CLEARED", "dependency", f"{upstream_app}->{downstream_app}", {})
        return {"source": upstream_app, "target": downstream_app, "outcome": None}
    by = _need(by, "the downstream owner's name")
    note = _need(note, "how the downstream application keeps working during the cutover", 10)
    row = store.insert("dependency_confirmations", {"id": cid, "project_id": pid, "kind": "BRIDGE", "source": upstream_app,
                                                    "target": downstream_app, "outcome": "BRIDGE_AGREED", "by_name": by, "note": note,
                                                    "recorded_at": now()})
    store.audit(pid, by, "BRIDGE_AGREED", "dependency", f"{upstream_app}->{downstream_app}", {"note": note})
    return row


# --------------------------------------------------------------------------- e-mail lifecycle
def effective(n: dict) -> dict:
    e = n.get("edited") or {}
    return {"to": n.get("recipient"), "subject": e.get("subject") or n.get("subject"), "body": e.get("body") or n.get("body")}


def text_hash(n: dict) -> str:
    return hashlib.sha256(json.dumps(effective(n), sort_keys=True).encode()).hexdigest()[:16]


def view(n: dict) -> dict:
    """Notification as shown: the approval state is derived (it lapses when the text changes), and the delivery state comes
    from what a person recorded."""
    n = dict(n)
    rec, tr = n.get("approval_rec") or {}, n.get("tracking") or {}
    if not rec:
        appr = "PENDING"
    elif rec.get("decision") == "REJECTED":
        appr = "REJECTED"
    elif tr.get("delivery") in ("SENT", "BOUNCED", "REPLIED") or rec.get("hash") == text_hash(n):
        appr = "APPROVED"
    else:
        appr = "CHANGED_SINCE_APPROVAL"
    eff = effective(n)
    n.update(approval=appr, delivery=tr.get("delivery") or "NOT_SENT", effective_subject=eff["subject"], effective_body=eff["body"],
             is_edited=bool(n.get("edited")))
    return n


def _row(store: Store, pid: str, nid: str) -> dict:
    n = store.get("notifications", nid)
    if not n or n["project_id"] != pid:
        raise KeyError(nid)
    return n


def _sendable(n: dict) -> None:
    if n["status"] != "DRAFT":
        raise ValueError("This draft has no verified recipient. Record the owner on Stakeholders first.")


def approve(store: Store, pid: str, nid: str, approver: str, decision: str, note: str = "") -> dict:
    n = _row(store, pid, nid)
    _sendable(n)
    if decision not in ("APPROVED", "REJECTED"):
        raise ValueError("Decision must be APPROVED or REJECTED.")
    if ((n.get("tracking") or {}).get("delivery") or "NOT_SENT") != "NOT_SENT":
        raise ValueError("This e-mail has already been sent; its approval cannot change.")
    approver = _need(approver, "your name")
    rec = {"decision": decision, "approver": approver, "note": (note or "").strip(), "at": now(), "hash": text_hash(n)}
    store.update("notifications", nid, approval_rec=rec, approval=decision, updated_at=now())
    store.record_approval(pid, "notification", nid, approver, decision, (note or "").strip() or f"{decision.lower()} as drafted",
                          requested_by="communication-agent")
    return view(store.get("notifications", nid))


def edit(store: Store, pid: str, nid: str, subject: str, body: str, editor: str) -> dict:
    n = _row(store, pid, nid)
    _sendable(n)
    if ((n.get("tracking") or {}).get("delivery") or "NOT_SENT") != "NOT_SENT":
        raise ValueError("This e-mail has already been sent; it can no longer be edited.")
    subject, body = _need(subject, "a subject", 5), _need(body, "the message", 20)
    editor = _need(editor, "your name")
    store.update("notifications", nid, edited={"subject": subject, "body": body, "by": editor, "at": now()}, updated_at=now())
    store.audit(pid, editor, "NOTIFICATION_EDITED", "notification", nid, {"subject": subject})
    return view(store.get("notifications", nid))


def track(store: Store, pid: str, nid: str, action: str, by: str, note: str = "", outcome: str = "", channel: str = "") -> dict:
    """action: SENT (a person sent it from their own mail client), BOUNCED, or REPLIED."""
    n = view(_row(store, pid, nid))
    _sendable(n)
    by = _need(by, "who is recording this")
    tr = dict(n.get("tracking") or {})
    cur = tr.get("delivery") or "NOT_SENT"
    if action == "SENT":
        if cur != "NOT_SENT":
            raise ValueError("Already recorded as sent.")
        if n["approval"] != "APPROVED":
            raise ValueError("Approve the current text before recording it as sent."
                             + (" It changed after it was approved." if n["approval"] == "CHANGED_SINCE_APPROVAL" else ""))
        eff = effective(n)
        tr.update(delivery="SENT", sent_by=by, sent_at=now(), channel=(channel or "e-mail").strip(), sent_snapshot=eff, history=[])
    elif action == "BOUNCED":
        if cur not in ("SENT",):
            raise ValueError("Only a sent e-mail can bounce.")
        tr.update(delivery="BOUNCED", bounce_note=_need(note, "what the bounce said", 3), bounce_by=by, bounce_at=now())
    elif action == "REPLIED":
        if cur not in ("SENT", "REPLIED"):
            raise ValueError("Record that it was sent before recording a reply.")
        if outcome not in REPLY_OUTCOMES:
            raise ValueError(f"Reply outcome must be one of {', '.join(REPLY_OUTCOMES)}.")
        note = _need(note, "what the reply said", 5)
        hist = list(tr.get("replies") or [])
        hist.append({"from": by, "outcome": outcome, "note": note, "at": now()})
        tr.update(delivery="REPLIED", replies=hist, last_reply=hist[-1])
    else:
        raise ValueError("Action must be SENT, BOUNCED or REPLIED.")
    store.update("notifications", nid, tracking=tr, updated_at=now())
    store.audit(pid, by, f"NOTIFICATION_{action}", "notification", nid,
                {"note": note, "outcome": outcome, "channel": channel, "sent_from_tool": False})
    return view(store.get("notifications", nid))


# --------------------------------------------------------------------------- drafting: upsert, never accumulate
CUTOVER = {
    ("MIGRATION_STARTED", True): ("Migration started – {about}",
        "Cutover of {about} to Google Cloud has started (recorded by {by}). {down_line}\n\n"
        "Action: watch for problems in {about} and its consumers and report them to the migration office."),
    ("MIGRATION_STARTED", False): ("Upstream migration started – {about} (used by {app})",
        "Cutover of {about} to Google Cloud has started (recorded by {by}). Your application {app} reads data that {about} produces. "
        "{bridge_line}\n\nAction: confirm that {app} keeps working, or report problems before the cutover completes."),
    ("MIGRATION_COMPLETED", True): ("Migration completed – {about}",
        "Cutover of {about} to Google Cloud is recorded as complete (recorded by {by}). The AWS source is kept as a fallback until it "
        "is decommissioned separately.\n\nAction: start post-cutover monitoring as agreed in the readiness review."),
    ("MIGRATION_COMPLETED", False): ("Upstream migration completed – {about} (used by {app})",
        "Cutover of {about} to Google Cloud is recorded as complete (recorded by {by}). {app} reads data that {about} produces. "
        "{bridge_line}\n\nAction: confirm that {app} now reads from the Google Cloud copy, or that the agreed bridge is still working."),
}


def cutover_drafts(statuses: dict[str, dict], stakeholders: list[dict], downstream_of: dict[str, set], brid: dict) -> list[tuple]:
    """(stakeholder, event, about_app, subject, body) for every application whose cutover started or completed: its own owners,
    and the owners of each application downstream of it."""
    out = []
    by_app: dict[str, list[dict]] = {}
    for s in stakeholders:
        by_app.setdefault(s["application"], []).append(s)
    for about, rec in sorted(statuses.items()):
        st = rec["status"]
        events = (["MIGRATION_STARTED"] if st in ("IN_PROGRESS", "MIGRATED") else []) + (["MIGRATION_COMPLETED"] if st == "MIGRATED" else [])
        downs = sorted(downstream_of.get(about, set()))
        for ev in events:
            for s in by_app.get(about, []):
                subj, body = CUTOVER[(ev, True)]
                f = {"about": about, "app": about, "by": rec["updated_by"],
                     "down_line": (f"Applications that read its data: {', '.join(downs)}." if downs else "No downstream applications were found.")}
                out.append((s, ev, about, subj.format(**f), body.format(**f)))
            for d in downs:
                b = brid.get((about, d))
                for s in by_app.get(d, []):
                    subj, body = CUTOVER[(ev, False)]
                    f = {"about": about, "app": d, "by": rec["updated_by"],
                         "bridge_line": (f"A bridge was agreed with {b['by_name']}: {b['note']}" if b else
                                         "No bridge has been recorded for your application.")}
                    out.append((s, ev, about, subj.format(**f), body.format(**f)))
    return out


def upsert_drafts(store: Store, pid: str, drafts: list[dict]) -> list[dict]:
    """Write this run's drafts under stable ids (project, recipient row, event, subject application), keeping what a person
    already did to each one (edit, approval, sent/reply records). Drafts that are no longer generated are removed unless a
    person already acted on them, in which case they stay as history."""
    keep_ids = set()
    out = []
    for d in drafts:
        nid = _sid("NTF-", pid, d.get("stakeholder_id") or "", d["event"], d.get("about_app") or "")
        old = store.get("notifications", nid) or {}
        row = {**d, "id": nid, "project_id": pid, "created_at": old.get("created_at") or d.get("created_at") or now(),
               "edited": old.get("edited"), "approval_rec": old.get("approval_rec"), "tracking": old.get("tracking"),
               "updated_at": now()}
        rec = old.get("approval_rec") or {}
        row["approval"] = rec.get("decision") or "PENDING"
        store.insert("notifications", row)
        keep_ids.add(nid)
        out.append(store.get("notifications", nid))
    for n in store.all("notifications", project_id=pid):
        if n["event"] == "SOURCE_CONFIRMATION_REQUEST" or n["id"] in keep_ids:
            continue
        if n.get("tracking") or n.get("approval_rec") or n.get("edited"):
            continue          # a person acted on it: keep as history
        store.delete_where("notifications", id=n["id"])
    return out


def all_notifications(store: Store, pid: str) -> list[dict]:
    rows = store.query("SELECT * FROM notifications WHERE project_id=? ORDER BY created_at, id", (pid,))
    return [view(r) for r in rows]


def summary(notes: list[dict]) -> dict:
    from collections import Counter
    a, d = Counter(n["approval"] for n in notes if n["status"] == "DRAFT"), Counter(n["delivery"] for n in notes)
    return {"total": len(notes), "blocked": sum(1 for n in notes if n["status"] != "DRAFT"),
            "approval": dict(a), "delivery": dict(d),
            "awaiting_reply": sum(1 for n in notes if n["delivery"] == "SENT"),
            "objections": sum(1 for n in notes if ((n.get("tracking") or {}).get("last_reply") or {}).get("outcome") == "OBJECTION")}


def valid_email(s: str) -> bool:
    return bool(re.match(r"^[^@\s]+@[^@\s]+\.[^@\s]+$", s or ""))
